def tex_escape(s):
    return s.replace("&", "\\&").replace("_", "\\_").replace("#", "\\#")


# ------------------------------------------------- 1. stationary distribution, 3 ways
def experiment_stationary(N=20):
    pi = models.ehrenfest_stationary(N)
    P, Plazy = models.ehrenfest(N), models.ehrenfest(N, lazy_chain=True)
    rows = []
    t = time.perf_counter(); x_lin = chain.stationary_linear(P); t_lin = time.perf_counter() - t
    rows.append(("Linear system (Gaussian elimination)", np.abs(x_lin - pi).max(), "--", t_lin))
    t = time.perf_counter(); x_pow, it = chain.stationary_power(Plazy, tol=1e-14); t_pow = time.perf_counter() - t
    rows.append(("Power iteration (lazy chain)", np.abs(x_pow - pi).max(), f"{it} iterations", t_pow))
    try:
        chain.stationary_power(P, max_iter=100_000)
        periodic_msg = "converged"
    except RuntimeError:
        periodic_msg = "does not converge (period 2)"
    n_sim = 1_000_000
    t = time.perf_counter(); path = chain.simulate(P, n_sim, start=0, rng=2026); t_sim = time.perf_counter() - t
    freq = chain.occupation_frequencies(path, N + 1)
    rows.append(("Simulation, occupation frequencies", np.abs(freq - pi).max(), f"{n_sim:,} steps", t_sim))

    md.extend([f"## 1. Ehrenfest urn with N = {N} balls: stationary distribution", "",
               "Exact answer: Binomial(N, 1/2) (detailed balance).", "",
               "| Method | max abs error vs Binomial | Cost | Time (ms) |", "|---|---|---|---|"])
    labels_fr = {"Linear system (Gaussian elimination)": "Système linéaire (Gauss)",
                 "Power iteration (lazy chain)": "Puissance (chaîne paresseuse)",
                 "Simulation, occupation frequencies": "Simulation (fréquences)"}
    rows_tex = []
    for name, err, cost, dt in rows:
        md.append(f"| {name} | {err:.1e} | {cost} | {dt * 1000:.1f} |")
        cost_tex = cost.replace(" iterations", " itérations").replace(" steps", " pas").replace(",", "\\,")
        rows_tex.append(f"{labels_fr[name]} & ${sci(max(err, 1e-17))}$ & {cost_tex} & {fr(dt * 1000, 1)} \\\\")
    md.extend(["", f"Power iteration on the plain (periodic) chain: {periodic_msg}.", ""])
    table("tableStationary", rows_tex)
    macro("nSim", thousands(n_sim))
    macro("powIters", str(it))

    # figure: distributions and distance to equilibrium
    start = np.zeros(N + 1)
    start[0] = 1.0
    n_max = 200
    plain = chain.distributions(start, P, n_max)
    lazy = chain.distributions(start, Plazy, n_max)
    cesaro = np.cumsum(plain, axis=0) / np.arange(1, n_max + 2)[:, None]
    lam_star = 1 - 1 / N
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    ks = np.arange(N + 1)
    ax1.bar(ks, pi, color=PURPLE, alpha=0.35, label="Binomial(20, 1/2) = pi")
    for n, c in ((5, GREY), (15, ORANGE), (60, DARK)):
        ax1.plot(ks, lazy[n], "o-", ms=3, lw=1.3, color=c, label=f"lazy chain, n = {n}")
    ax1.set_xlabel("k = balls in urn A")
    ax1.set_ylabel("probability")
    ax1.set_title("Distribution of X_n, starting from k = 0")
    ax1.legend(fontsize=8)
    n = np.arange(n_max + 1)
    ax2.semilogy(n, [chain.tv_distance(m, pi) for m in plain], color=GREY, lw=1.5, label="plain chain (period 2)")
    ax2.semilogy(n, [chain.tv_distance(m, pi) for m in cesaro], color=PURPLE, lw=1.5, label="plain chain, Cesaro average")
    ax2.semilogy(n, [chain.tv_distance(m, pi) for m in lazy], color=ORANGE, lw=1.8, label="lazy chain")
    ax2.semilogy(n, chain.tv_bound(pi[0], lam_star, n), "--", color=ORANGE, lw=1, alpha=0.7, label="spectral bound")
    ax2.set_ylim(1e-5, 2)
    ax2.set_xlabel("n")
    ax2.set_ylabel("total variation distance to pi")
    ax2.set_title("Convergence needs aperiodicity")
    ax2.legend(fontsize=8)
    save(fig, "1_ehrenfest")


# ------------------------------------------------------ 2. speed and spectral gap
def experiment_spectral_gap():
    sizes = [10, 20, 40]
    colors = [ORANGE, PURPLE, DARK]
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    md.extend(["## 2. Convergence speed and spectral gap", "",
               "Lazy random walk on the cycle Z/mZ: lambda_2 = cos^2(pi/m). Lazy Ehrenfest urn: lambda_2 = 1 - 1/N.", "",
               "| Chain | lambda_2 (theory) | Observed rate | Mixing time t_mix(1/4) |", "|---|---|---|---|"])
    rows_tex = []
    for m, c in zip(sizes, colors):
        P = models.cycle_walk(m)
        pi = np.full(m, 1.0 / m)
        start = np.zeros(m)
        start[0] = 1.0
        n_max = 12 * m * m
        d = np.array([chain.tv_distance(mu, pi) for mu in chain.distributions(start, P, n_max)])
        lam2 = models.cycle_lambda2(m)
        ok = np.nonzero(d > 1e-13)[0]
        rate = chain.observed_rate(d, start=int(ok[-1] * 0.4), stop=int(ok[-1]))
        tmix = chain.mixing_time(P, 0.25, pi=pi)
        ax1.semilogy(np.arange(n_max + 1), np.maximum(d, 1e-17), color=c, lw=1.6, label=f"m = {m}")
        ax1.semilogy(np.arange(n_max + 1), chain.tv_bound(1.0 / m, lam2, np.arange(n_max + 1)), "--", color=c, lw=0.9, alpha=0.6)
        md.append(f"| Cycle, m = {m} | {lam2:.6f} | {rate:.6f} | {tmix} |")
        rows_tex.append(f"Cycle, $m = {m}$ & {fr(lam2, 6)} & {fr(rate, 6)} & {tmix} \\\\")
    for N in (20, 50):
        P = models.ehrenfest(N, lazy_chain=True)
        pi = models.ehrenfest_stationary(N)
        start = np.zeros(N + 1)
        start[0] = 1.0
        d = np.array([chain.tv_distance(mu, pi) for mu in chain.distributions(start, P, 30 * N)])
        ok = np.nonzero(d > 1e-13)[0]
        rate = chain.observed_rate(d, start=int(ok[-1] * 0.4), stop=int(ok[-1]))
        tmix = chain.mixing_time(P, 0.25, pi=pi)
        md.append(f"| Lazy Ehrenfest, N = {N} | {1 - 1 / N:.6f} | {rate:.6f} | {tmix} |")
        rows_tex.append(f"Ehrenfest paresseuse, $N = {N}$ & {fr(1 - 1 / N, 6)} & {fr(rate, 6)} & {tmix} \\\\")
    ax1.set_ylim(1e-14, 2)
    ax1.set_xlim(0, 5500)
    ax1.set_xlabel("n")
    ax1.set_ylabel("||mu_n - pi||_TV")
    ax1.set_title("Lazy walk on a cycle of m sites (dashed: spectral bound)")
    ax1.legend(fontsize=8)
    table("tableGap", rows_tex)

    ms = np.array([8, 12, 16, 24, 32, 48, 64, 96, 128])
    tm = np.array([chain.mixing_time(models.cycle_walk(int(m)), 0.25, pi=np.full(int(m), 1.0 / m)) for m in ms])
    trel = 1 / (1 - np.array([models.cycle_lambda2(int(m)) for m in ms]))
    slope = np.polyfit(np.log(ms), np.log(tm), 1)[0]
    ax2.loglog(ms, tm, "o-", color=ORANGE, label=f"mixing time t_mix(1/4) (slope {slope:.2f})")
    ax2.loglog(ms, trel, "--", color=GREY, label="relaxation time 1/(1 - lambda_2) ~ m^2/pi^2")
    ax2.set_xlabel("m (number of sites)")
    ax2.set_ylabel("steps")
    ax2.set_title("Mixing time grows like m^2 (diffusion)")
    ax2.legend(fontsize=8)
    save(fig, "2_spectral_gap")
    md.extend(["", "Mixing time of the lazy cycle walk:", "", "| m | t_mix(1/4) | 1/(1 - lambda_2) |", "|---|---|---|"])
    md.extend(f"| {m} | {t} | {r:.1f} |" for m, t, r in zip(ms, tm, trel))
    md.extend(["", f"Log-log slope of t_mix against m: {slope:.3f} (theory: 2).", ""])
    macro("mixSlope", fr(slope, 2))
    macro("mixHundred", str(int(tm[list(ms).index(128)])))


# --------------------------------------------- 3. ergodic theorem and Monte Carlo
def experiment_monte_carlo(g, exact):
    N = 20
    pi = models.ehrenfest_stationary(N)
    P = models.ehrenfest(N)
    checkpoints = np.unique(np.logspace(2, 5.3, 12).astype(int))
    reps = 400
    freqs = chain.occupation_many(P, int(checkpoints[-1]), reps, checkpoints, start=0, rng=2026)
    errs = np.array([[chain.tv_distance(f, pi) for f in fc] for fc in freqs]).T     # (reps, checkpoints)
    mean_err = errs.mean(axis=0)
    slope1 = np.polyfit(np.log(checkpoints[2:]), np.log(mean_err[2:]), 1)[0]

    walks = np.array([1_000, 3_000, 10_000, 30_000, 100_000, 300_000, 1_000_000])
    err_mc = []
    times = []
    for n in walks:
        t = time.perf_counter()
        est = pr.pagerank_monte_carlo(g, 0.85, int(n), rng=int(n))
        times.append(time.perf_counter() - t)
        err_mc.append(np.abs(est - exact).sum())
    err_mc = np.array(err_mc)
    slope2 = np.polyfit(np.log(walks), np.log(err_mc), 1)[0]
    top = np.argsort(-exact)[:10]
    est = pr.pagerank_monte_carlo(g, 0.85, 1_000_000, rng=7)
    same_top10 = int(np.sum(np.isin(np.argsort(-est)[:10], top)))

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    ax1.loglog(checkpoints, mean_err, "o-", color=ORANGE, label=f"mean over {reps} chains (slope {slope1:.2f})")
    ax1.loglog(checkpoints, mean_err[-1] * np.sqrt(checkpoints[-1] / checkpoints), "--", color=GREY, label="C / sqrt(n)")
    ax1.set_xlabel("trajectory length n")
    ax1.set_ylabel("TV(occupation frequencies, pi)")
    ax1.set_title("Ergodic theorem: Ehrenfest urn, N = 20")
    ax1.legend(fontsize=8)
    ax2.loglog(walks, err_mc, "o-", color=PURPLE, label=f"Monte Carlo PageRank (slope {slope2:.2f})")
    ax2.loglog(walks, err_mc[-1] * np.sqrt(walks[-1] / walks), "--", color=GREY, label="C / sqrt(walks)")
    ax2.set_xlabel("number of random walks")
    ax2.set_ylabel("L1 error vs power method")
    ax2.set_title("Random surfers estimate PageRank (airports)")
    ax2.legend(fontsize=8)
    save(fig, "3_monte_carlo")

    md.extend(["## 3. Monte Carlo: the ergodic theorem and random surfers", "",
               f"Ehrenfest urn (periodic chain) started at 0, occupation frequencies, mean over {reps} independent chains:", "",
               "| n | mean TV error |", "|---|---|"])
    md.extend(f"| {n:,} | {e:.2e} |" for n, e in zip(checkpoints, mean_err))
    md.extend(["", f"Slope: {slope1:.3f} (theory: -1/2).", "",
               "PageRank of the airline network estimated by the end points of random walks (alpha = 0.85):", "",
               "| Walks | L1 error | Time (s) |", "|---|---|---|"])
    md.extend(f"| {n:,} | {e:.4f} | {t:.2f} |" for n, e, t in zip(walks, err_mc, times))
    md.extend(["", f"Slope: {slope2:.3f} (theory: -1/2). With 1,000,000 walks, {same_top10} of the true top 10 airports are in the estimated top 10.", ""])
    macro("slopeErgodic", fr(slope1, 2))
    macro("nChains", str(reps))
    macro("slopeMC", fr(slope2, 2))
    macro("errMCmillion", fr(err_mc[-1], 3))
    macro("sameTopTen", str(same_top10))
    table("tableMC", [f"{thousands(int(n))} & {fr(e, 4)} & {fr(t, 2)} \\\\" for n, e, t in zip(walks, err_mc, times)])


# ------------------------------------------- 4. power method: speed against alpha
def experiment_convergence(g):
    alphas = [0.5, 0.7, 0.85, 0.95, 0.99]
    colors = [GREY, GREEN, ORANGE, PURPLE, DARK]
    fig, ax = plt.subplots(figsize=(7.2, 4.2))
    md.extend(["## 4. Power method: convergence speed against alpha", "",
               "Error ||x_k - pi||_1 starting from the uniform vector; pi is computed to 1e-15. Theory: error <= alpha^k ||x_0 - pi||_1.", "",
               "| alpha | Observed rate | Iterations to error < 1e-10 | Guaranteed by the bound | Time (ms) |", "|---|---|---|---|---|"])
    rows_tex = []
    for a, c in zip(alphas, colors):
        exact = pr.pagerank(g, a, tol=1e-15, max_iter=100_000).scores
        x = np.full(g.n, 1.0 / g.n)
        v = x.copy()
        e0 = np.abs(x - exact).sum()
        errs = [e0]
        kmax = 400 if a < 0.99 else 3000
        t = time.perf_counter()
        for _ in range(kmax):
            x = pr.google_step(g, x, a, v)
            errs.append(np.abs(x - exact).sum())
        dt = (time.perf_counter() - t) / kmax
        errs = np.array(errs)
        hit = np.nonzero(errs < 1e-10)[0]
        it = int(hit[0]) if hit.size else None
        bound_it = int(np.ceil(np.log(1e-10 / e0) / np.log(a)))
        ok = np.nonzero(errs > 1e-11)[0]          # stay well above the rounding floor (~1e-14)
        rate = chain.observed_rate(errs, start=int(ok[-1]) // 2, stop=int(ok[-1]))
        k = np.arange(len(errs))
        last = int(np.nonzero(errs > 3e-14)[0][-1]) + 1          # hide the flat part at the rounding floor
        ax.semilogy(k[:last], errs[:last], color=c, lw=1.7, label=f"alpha = {a} (rate {rate:.3f})")
        ax.semilogy(k, e0 * a ** k, ":", color=c, lw=1)
        md.append(f"| {a} | {rate:.4f} | {it if it is not None else '> %d' % kmax} | {bound_it} | {dt * 1e3 * (it or kmax):.0f} |")
        rows_tex.append(f"{fr(a, 2)} & {fr(rate, 4)} & {it if it is not None else '$> %d$' % kmax} & {bound_it} \\\\")
        if a == 0.85:
            macro("itersEightyFive", str(it))
            macro("boundEightyFive", str(bound_it))
            macro("msPerIter", fr(dt * 1e3, 2))
    ax.set_ylim(1e-14, 5)
    ax.set_xlim(0, 400)
    ax.set_xlabel("iteration k")
    ax.set_ylabel("||x_k - pi||_1")
    ax.set_title("PageRank power method on the airline network (dotted: alpha^k bound)")
    ax.legend(fontsize=8, loc="upper right")
    save(fig, "4_convergence")
    md.append("")
    table("tableAlpha", rows_tex)


# ------------------------------------------------------ 5. the airline network
def experiment_airports(g, codes, info):
    import networkx as nx  # only used to check the results

    t = time.perf_counter(); res = pr.pagerank(g, 0.85, tol=1e-14); t_ours = time.perf_counter() - t
    G = nx.DiGraph()
    G.add_nodes_from(range(g.n))
    G.add_weighted_edges_from(zip(g.src.tolist(), g.dst.tolist(), g.w.tolist()))
    t = time.perf_counter(); ref = nx.pagerank(G, alpha=0.85, weight="weight", tol=1e-15, max_iter=1000); t_nx = time.perf_counter() - t
    ref = np.array([ref[i] for i in range(g.n)])
    diff = float(np.abs(ref - res.scores).max())
    scores = res.scores
    indeg = g.in_weight()
    rank_pr, rank_deg = pr.ranking(scores), pr.ranking(indeg)
    rho = pr.spearman(scores, indeg)
    alg = codes.index("ALG")
    comp = pr.strongly_connected_components(g)
    largest = int(np.bincount(comp).max())
    closed = pr.closed_classes(g, comp)
    closed_sizes = sorted((int(np.sum(comp == c)) for c in closed), reverse=True)

    macro("nAirports", thousands(g.n))
    macro("nRoutes", thousands(len(g.src)))
    macro("nRouteEntries", thousands(int(g.w.sum())))
    macro("nDangling", str(int(g.dangling.sum())))
    macro("prIters", str(res.iterations))
    macro("diffNX", sci(diff))
    macro("timeOurs", fr(t_ours * 1000, 0))
    macro("timeNX", fr(t_nx * 1000, 0))
    macro("spearmanDeg", fr(rho, 3))
    macro("algRank", str(int(rank_pr[alg])))
    macro("algDegRank", str(int(rank_deg[alg])))
    macro("algScore", sci(scores[alg], 2))
    macro("uniformScore", sci(1 / g.n, 2))
    macro("nSCC", str(int(comp.max() + 1)))
    macro("largestSCC", thousands(largest))
    macro("nClosed", str(len(closed)))
    macro("closedSizes", ", ".join(str(x) for x in closed_sizes))

    md.extend(["## 5. The world airline network (OpenFlights, routes as of June 2014)", "",
               f"{g.n} airports, {len(g.src)} directed routes (airport pairs), weighted by the number of airlines "
               f"({int(g.w.sum())} airline routes in total); {int(g.dangling.sum())} airports have no outgoing route.", "",
               f"PageRank (alpha = 0.85): {res.iterations} iterations, guaranteed L1 error {res.error_bound:.1e}, {t_ours * 1000:.0f} ms. "
               f"NetworkX: {t_nx * 1000:.0f} ms. Largest difference with NetworkX: {diff:.1e}.", "",
               f"Strongly connected components: {comp.max() + 1}, the largest has {largest} airports. "
               f"Closed classes (no route leaves them): {len(closed)}, of sizes {closed_sizes}; with two or more, |lambda_2(G)| = alpha.", "",
               f"Spearman correlation between PageRank and weighted in-degree: {rho:.3f}.", "",
               f"Algiers (ALG): PageRank rank {rank_pr[alg]} of {g.n} (score {scores[alg]:.2e}, uniform would be {1 / g.n:.2e}); in-degree rank {rank_deg[alg]}.", "",
               "| Rank | Airport | City, country | PageRank (x 1000) | In-degree rank |", "|---|---|---|---|---|"])
    top = np.argsort(-scores)[:15]
    rows_tex = []
    for r, i in enumerate(top, 1):
        c = codes[i]
        it = info.get(c, {"name": c, "city": "", "country": ""})
        md.append(f"| {r} | {c} {it['name']} | {it['city']}, {it['country']} | {scores[i] * 1000:.3f} | {rank_deg[i]} |")
        rows_tex.append(f"{r} & \\texttt{{{c}}} & {tex_escape(fr_name(it['city']))} ({tex_escape(fr_name(it['country']))}) & {fr(scores[i] * 1000, 3)} & {rank_deg[i]} \\\\")
    table("tableTop", rows_tex)

    # airports promoted or demoted by PageRank compared with the number of incoming routes (top 100 by PageRank)
    cand = np.argsort(-scores)[:100]
    gain = rank_deg[cand] - rank_pr[cand]
    up = cand[np.argsort(-gain)[:5]]
    md.extend(["", "Largest gains of PageRank over in-degree among the top 100:", "",
               "| Airport | PageRank rank | In-degree rank |", "|---|---|---|"])
    rows_up = []
    for i in up:
        it = info.get(codes[i], {"city": "", "country": ""})
        md.append(f"| {codes[i]} ({it['city']}, {it['country']}) | {rank_pr[i]} | {rank_deg[i]} |")
        rows_up.append(f"\\texttt{{{codes[i]}}} & {tex_escape(fr_name(it['city']))} ({tex_escape(fr_name(it['country']))}) & {rank_pr[i]} & {rank_deg[i]} \\\\")
    table("tableUp", rows_up)
    md.append("")

    # figure 5: world map
    lon = np.array([info[c]["lon"] if c in info else np.nan for c in codes])
    lat = np.array([info[c]["lat"] if c in info else np.nan for c in codes])
    order = np.argsort(scores)
    fig, ax = plt.subplots(figsize=(11, 4.9))
    sizes = 2 + 4.5e4 * scores
    sc = ax.scatter(lon[order], lat[order], s=sizes[order], c=np.log10(scores[order]), cmap="plasma", alpha=0.8, linewidths=0)
    placed = []
    for i in np.argsort(-scores)[:25]:
        if any(np.hypot(lon[i] - x, lat[i] - y) < 11 for x, y in placed) or len(placed) >= 11:
            continue
        placed.append((lon[i], lat[i]))
        ax.annotate(codes[i], (lon[i], lat[i]), xytext=(5, 4), textcoords="offset points", fontsize=8, fontweight="bold", color=DARK)
    ax.annotate("ALG", (lon[alg], lat[alg]), xytext=(4, -9), textcoords="offset points", fontsize=8, color=ORANGE, fontweight="bold")
    ax.set_xlim(-180, 180)
